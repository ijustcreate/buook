function ink(p,text,x,y,size=2,hand='keeper') {
  const letters=String(text).toUpperCase().replace(/[’‘]/g,"'").replace(/[—–]/g,'-');
  let pen=x;
  [...letters].forEach((letter,index)=>{
    if(letter===' '){pen+=size*3.4;return;}
    const glyph=INK_GLYPHS[letter]||INK_GLYPHS['?'];
    const offset=(index%5===2?1:0)*size*.35;
    glyph.split('/').forEach((row,ry)=>[...row].forEach((bit,rx)=>{
      if(bit!=='1')return;
      const lean=hand==='wanderer'?(6-ry)*.19:hand==='grudge'?ry*.08:0;
      p.fillRect(Math.round(pen+(rx+lean)*size),Math.round(y+ry*size+offset),Math.ceil(size+(hand==='grudge'?.35:0)),Math.ceil(size));
    }));
    pen+=size*6;
  });
  return pen-x;
}
